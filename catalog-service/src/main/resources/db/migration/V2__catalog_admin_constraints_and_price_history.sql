ALTER TABLE skus ADD CONSTRAINT uk_skus_product_variant UNIQUE (product_id, color, size);

CREATE TABLE sku_price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_id BIGINT NOT NULL REFERENCES skus(id),
    old_price BIGINT,
    new_price BIGINT NOT NULL CHECK (new_price > 0),
    reason VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_sku_price_history_sku_created ON sku_price_history(sku_id, created_at DESC);
